import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { readSchedule, parseBricks } from '../parser.mjs';
import { readCredits } from '../credits.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const base = 'http://127.0.0.1:8788';
const child = spawn(process.execPath, ['server.mjs'], { cwd: root, env: { ...process.env, PORT: '8788' }, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
try {
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Serveren startede ikke')), 10000);
    child.stdout.on('data', chunk => { if (chunk.toString().includes(base)) { clearTimeout(timeout); resolve(); } });
    child.once('error', reject);
    child.once('exit', code => { clearTimeout(timeout); reject(new Error('Server exit ' + code)); });
  });
  assert.equal((await fetch(base + '/api/status', { headers: { Origin: 'https://evil.example' } })).status, 403);
  assert.equal((await fetch(base + '/api/config', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  browser = await chromium.launch();
  const fixturePage = await browser.newPage();
  await fixturePage.setContent('<div class="s2weekHeader">Uge 43</div><a class="s2skemabrik s2cancelled" href="aktivitet.aspx?absid=77" data-tooltip="Biologi&#10;19/10-2026 08:10 til 09:45&#10;Hold: 2x&#10;Lærer: SM&#10;Lokale: 12">sms Biologi</a><a class="s2skemabrik s2normal" data-tooltip="Skolearrangement&#10;19/10-2026 Hele dagen">• Skolearrangement</a>');
  const extracted = await fixturePage.evaluate(readSchedule);
  assert.equal(extracted.recognized, true);
  assert.equal(extracted.login, false);
  const parsed = parseBricks(extracted.bricks, 'https://www.lectio.dk/lectio/141/SkemaNy.aspx');
  assert.equal(parsed.events[1].activityId, '77');
  assert.equal(parsed.events[1].cancelled, true);
  assert.equal(parsed.events[0].allDay, true);
  assert.deepEqual(parsed.warnings, []);
  await fixturePage.setContent('<input type="password">');
  assert.equal((await fixturePage.evaluate(readSchedule)).login, true);
  await fixturePage.setContent('<p>Service utilgængelig</p>');
  assert.equal((await fixturePage.evaluate(readSchedule)).recognized, false);
  const creditFixture = checked => `<table><tr><th>Krediteret lærer</th><th>Hold</th><th>Kreditér</th><th>Moduler</th><th>Ekstra timer</th><th>Krediteringsnote</th><th>Krediterings&shy;rolle</th><th>Aflysnings årsag</th></tr><tr><td>AA</td><td><select><option selected>2x</option><option>Andet hold</option></select></td><td><input type="checkbox" ${checked ? 'checked' : ''}></td><td><input disabled value="1"></td><td><input value="0,00"></td><td><input value=""></td><td><select><option selected>Auto</option></select></td><td><select><option selected>${checked ? 'Sygdom' : ''}</option><option>Andet</option><option>Kurser</option></select></td></tr></table><table><tr><th>Krediteret hold</th><th>Kreditér</th><th>Moduler</th></tr><tr><td>2x</td><td><input type="checkbox" ${checked ? 'checked' : ''}></td><td><input disabled value="1"></td></tr></table>`;
  for (const checked of [false, true]) {
    await fixturePage.setContent(creditFixture(checked));
    const credits = await fixturePage.evaluate(readCredits);
    assert.equal(credits.status, 'ok');
    assert.equal(credits.teachers[0].credited, checked);
    assert.equal(credits.groups[0].credited, checked);
    assert.equal(credits.teachers[0].modules, 1);
    assert.equal(credits.teachers[0].extraHours, 0);
    assert.equal(credits.teachers[0].group, '2x');
    assert.equal(credits.teachers[0].cancellationReason, checked ? 'Sygdom' : '');
  }
  await fixturePage.setContent(creditFixture(false).replaceAll('type="checkbox"', 'type="hidden"'));
  const missingCredits = await fixturePage.evaluate(readCredits);
  assert.equal(missingCredits.status, 'unknown');
  assert.equal(missingCredits.teachers[0].credited, null);
  await fixturePage.setContent('<input type="password">');
  assert.equal((await fixturePage.evaluate(readCredits)).status, 'unknown');
  parsed.events[1].credits = { status: 'ok', teachers: [{ teacher: 'AA', credited: true, modules: 1, role: 'Auto', cancellationReason: 'Sygdom' }], groups: [{ group: '2x', credited: false, modules: 1 }] };
  await mkdir(root + 'test/ud', { recursive: true });
  for (const width of [390, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const state = { config: { url: 'https://www.lectio.dk/lectio/141/SkemaNy.aspx', week: '432026' }, status: '2 aktiviteter hentet fra Lectio.', needsLogin: false, lastAttempt: '2026-10-15T12:00:00Z', snapshot: null };
    let fail = false;
    const modes = [];
    await page.route('**/api/**', route => {
      const endpoint = new URL(route.request().url()).pathname;
      if (endpoint === '/api/sync') modes.push(route.request().postDataJSON().mode);
      if (endpoint === '/api/sync' && fail) return route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ error: 'Sessionen er udløbet. Log ind igen.' }) });
      if (endpoint === '/api/sync') state.snapshot = { range: { from: '2026-08-01', to: '2026-12-31' }, weeks: ['312026', '432026', '532026'], source: state.config.url, fetchedAt: '2026-10-15T12:00:00Z', events: [{ ...parsed.events[1], id: 'august', start: '2026-08-17T08:10:00', end: '2026-08-17T09:45:00' }, ...parsed.events, { ...parsed.events[1], id: '88', title: '<img src=x onerror=alert(1)>', start: '2026-10-20T10:00:00', end: '2026-10-20T11:00:00', cancelled: false, changed: true }] };
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify(endpoint === '/api/status' ? state : {}) });
    });
    await page.goto(base);
    await page.waitForFunction(() => document.getElementById('url').value.includes('/141/'));
    assert.equal(await page.locator('.empty').count(), 1);
    await page.click('#sync');
    await page.waitForSelector('.event');
    assert.equal(await page.locator('.event').count(), 4);
    await page.selectOption('#month', '2026-10');
    assert.equal(await page.locator('.event').count(), 3);
    await page.selectOption('#month', '');
    assert.equal(await page.locator('.event').count(), 4);
    await page.check('#cancelled-only');
    assert.equal(await page.locator('.event').count(), 2);
    await page.uncheck('#cancelled-only');
    assert.equal(await page.locator('.event').count(), 4);
    assert.equal(await page.getByText('Hele dagen', { exact: true }).count(), 1);
    assert.match(await page.locator('#days').textContent(), /Lærer AA: ja \(1 modul\)/);
    assert.match(await page.locator('#days').textContent(), /Hold 2x: nej/);
    assert.equal(await page.locator('.event img').count(), 0);
    assert.equal(await page.locator('#download').isVisible(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: root + `test/ud/skema-${width}.png`, fullPage: true });
    await page.click('#sync-all');
    await page.waitForFunction(() => !document.getElementById('sync-all').disabled);
    assert.deepEqual(modes, ['future', 'all']);
    fail = true; await page.click('#sync'); await page.waitForSelector('#notice.error');
    assert.equal(await page.locator('.event').count(), 4);
    assert.match(await page.locator('#notice').textContent(), /udløbet/);
    assert.deepEqual(errors, []);
    await page.close();
  }
  console.log('OK: DOM-parser, adgangskontrol, mobil/desktop, JSON-link, tekstsikkerhed og bevaret skema ved loginfejl.');
} finally { await browser?.close(); child.kill('SIGTERM'); }
